  cerrar_inscripcion_al_iniciar_primer_encuentro BOOLEAN DEFAULT false,
  first_encounter_date TEXT,
  first_encounter_start_time TEXT,
  first_encounter_end_time TEXT,
  enrolled BOOLEAN DEFAULT false,
  capacity INT DEFAULT 20,
  enrolled_count INT DEFAULT 0,
  short_description TEXT,
  description TEXT,
  image TEXT,
  is_approved BOOLEAN DEFAULT true,
  proposal_status TEXT DEFAULT 'aprobada',
  baja_forzada BOOLEAN DEFAULT false,
  baja_date TEXT,
  baja_reason TEXT,
  baja_admin TEXT,
  proposal_note TEXT,
  vetted_users JSONB DEFAULT '[]'::jsonb,
  enrolled_usernames JSONB DEFAULT '[]'::jsonb,
  versions JSONB DEFAULT '[]'::jsonb,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 3. TABLA: CHATS (Canales y Conversaciones)
-- Enum chat_type: 'grupo_actividad', 'grupo_libre', 'privado'
DO $$ BEGIN
  CREATE TYPE chat_type AS ENUM ('grupo_actividad', 'grupo_libre', 'privado');
EXCEPTION
  WHEN duplicate_object THEN null;
END $$;

CREATE TABLE IF NOT EXISTS public.chats (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  nombre TEXT NOT NULL,
  tipo chat_type NOT NULL DEFAULT 'grupo_libre', -- 'grupo_actividad', 'grupo_libre', 'privado'
  actividad_id BIGINT REFERENCES public.activities(id) ON DELETE SET NULL,
  creador_id TEXT REFERENCES public.users(id) ON DELETE SET NULL,
  foto_grupo_url TEXT,
  creado_el TIMESTAMPTZ DEFAULT now()
);

-- 3b. TABLA: CHAT_PARTICIPANTS (Miembros y Participantes de Chats)
CREATE TABLE IF NOT EXISTS public.chat_participants (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  chat_id UUID NOT NULL REFERENCES public.chats(id) ON DELETE CASCADE,
  user_id TEXT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  joined_at TIMESTAMPTZ DEFAULT now(),
  UNIQUE (chat_id, user_id)
);

-- 4. TABLA: MESSAGES (Mensajes en tiempo real)
