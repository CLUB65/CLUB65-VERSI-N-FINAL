-- 1. TABLA: USERS (Usuarios y Perfiles Comunitarios)
CREATE TABLE IF NOT EXISTS public.users (
  id TEXT PRIMARY KEY,
  usuario TEXT UNIQUE NOT NULL,
  email TEXT,
  clave TEXT,
  apodo TEXT NOT NULL,
  avatar TEXT,
  bio TEXT,
  text_size TEXT DEFAULT 'normal',
  contrast BOOLEAN DEFAULT false,
  tipo TEXT DEFAULT 'personal', -- 'personal', 'institucional', 'moderador'
  rol TEXT DEFAULT 'personal',  -- 'personal', 'institucional', 'moderador'
  localidad TEXT DEFAULT 'Tres de Febrero',
  is_verified BOOLEAN DEFAULT false,
  estado_alta TEXT DEFAULT 'aprobada', -- 'pendiente', 'aprobada', 'rechazada'
  entidad_tipo TEXT,
  cuit TEXT,
  legal_representative TEXT,
  contacto_institucional TEXT,
  documento_cuit_url TEXT,
  documento_personeria_url TEXT,
  blocked_users JSONB DEFAULT '[]'::jsonb,
  notifications JSONB DEFAULT '[]'::jsonb,
  created_at TIMESTAMPTZ DEFAULT now()
);

