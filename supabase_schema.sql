-- 2. Sincronización de datos previos (sin pérdida de información)
DO $$ 
BEGIN
  -- Unificar rol y role en 'rol'
  IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'users' AND column_name = 'role') THEN
    UPDATE public.users 
    SET rol = COALESCE(NULLIF(rol, ''), NULLIF(role, ''), 'personal')
    WHERE rol IS NULL OR rol = '' OR role IS NOT NULL;
  ELSE
    UPDATE public.users 
    SET rol = COALESCE(NULLIF(rol, ''), 'personal')
    WHERE rol IS NULL OR rol = '';
  END IF;

  -- Unificar estado_alta y estado_institucion en 'estado_alta'
  IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'users' AND column_name = 'estado_institucion') THEN
    UPDATE public.users 
    SET estado_alta = COALESCE(NULLIF(estado_alta, ''), NULLIF(estado_institucion, ''), 'aprobada')
    WHERE estado_alta IS NULL OR estado_alta = '' OR estado_institucion IS NOT NULL;
  ELSE
    UPDATE public.users 
    SET estado_alta = COALESCE(NULLIF(estado_alta, ''), 'aprobada')
    WHERE estado_alta IS NULL OR estado_alta = '';
  END IF;

  -- Unificar telefono_institucional y contacto_institucional en 'contacto_institucional'
  IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'users' AND column_name = 'telefono_institucional') THEN
    UPDATE public.users 
    SET contacto_institucional = COALESCE(NULLIF(contacto_institucional, ''), NULLIF(telefono_institucional, ''))
    WHERE contacto_institucional IS NULL OR contacto_institucional = '' OR telefono_institucional IS NOT NULL;
  END IF;
END $$;

-- 3. Eliminación segura de columnas redundantes
ALTER TABLE public.users 
  DROP COLUMN IF EXISTS role,
  DROP COLUMN IF EXISTS estado_institucion,
  DROP COLUMN IF EXISTS telefono_institucional;

